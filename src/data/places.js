const FLAT = Object.entries(PLACES).flatMap(([country, list]) =>
    list.map(([name, lat, lon]) => ({ name, country, lat, lon })));

const toRad = (d) => (d * Math.PI) / 180;
function distanceKm(aLat, aLon, bLat, bLon) {
    const dLat = toRad(bLat - aLat);
    const dLon = toRad(bLon - aLon);
    const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(aLat)) * Math.cos(toRad(bLat)) * Math.sin(dLon / 2) ** 2;
    return 2 * 6371 * Math.asin(Math.sqrt(h));
}

/* Nearest known place to a coordinate. Within 120 km we trust the city;
   further out we only trust the country (e.g. a photo from a national park). */
export function placeFromCoords(lat, lon) {
    let best = null;
    let bestD = Infinity;
    for (const p of FLAT) {
        const d = distanceKm(lat, lon, p.lat, p.lon);
        if (d < bestD) { bestD = d; best = p; }
    }
    if (!best) return null;
    return bestD <= 120
        ? { place: best.name, country: best.country }
        : { place: best.country, country: '' };
}
